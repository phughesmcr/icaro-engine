// Facade: the model code is split by the C file's sections, and this module
// re-exports the names its importers use, so they need not change.
//   mod_types.js        constants and structs (gl_model.h, modelgen.h,
//                       spritegn.h)
//   model.js            the model cache: Mod_Init, Mod_ForName, PVS helpers
//   mod_brush.js        BRUSHMODEL LOADING (Mod_LoadBrushModel)
//   mod_alias.js        ALIAS MODELS (Mod_LoadAliasModel, MD5 replacements)
//   mod_sprite.js       SPRITE MODELS (Mod_LoadSpriteModel)
//   gl_model_upload.js  Three.js textures, sky layers and the gl_warp,
//                       gl_mesh and gl_md5 calls the loaders make
// mod_types.js comes first: model.js and mod_alias.js build its structs at
// module load.

